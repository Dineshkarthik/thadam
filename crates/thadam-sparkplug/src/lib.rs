//! Sparkplug B decode building blocks for Thadam (Sparkplug specification
//! 3.0.0, `spBv1.0` topic namespace; the evaluation and design analysis live
//! in `docs/design/spikes/sparkplug-b-and-opcua-pubsub.md`):
//!
//! - [`pb`]: the wire schema, compiled at build time into a prost
//!   `Payload`,
//! - [`topic`]: the `spBv1.0/<group>/<kind>/<edge node>[/<device>]`
//!   namespace parser,
//! - [`decode`]: the stateful decoder — BIRTH registration, alias-only DATA
//!   resolution, 0–255 seq gap/wrap tracking, bdSeq sessions, DEATH
//!   staleness, rebirth — seeded across restarts from
//!   [`thadam_core::BirthStore`].
//!
//! # Wire-schema provenance
//!
//! `proto/sparkplug_b.proto` was written for Thadam (Apache-2.0) from the
//! message definitions and field numbers the Sparkplug specification 3.0.0
//! publishes in chapter 6 ("Payloads") — protocol constants every
//! implementation must share — with the normative prose behind each message
//! cited inline by section and `[tck-id-*]` marker (owner decision O-1). It
//! is not the Eclipse Tahu file: no Tahu license header, comment, or text
//! was carried over.
//!
//! # Purity
//!
//! The decoder does no I/O of its own. Each message's durable consequences
//! come back as [`decode::StoreUpdate`]s the caller applies to a
//! [`thadam_core::BirthStore`] (step 1b wires that into the transform chain
//! as `decode: sparkplug_b`), and a restart rebuilds the decoder with
//! [`decode::Decoder::seeded`] from [`thadam_core::BirthStore::load_all`].
//! That keeps the state machine testable in memory.

pub mod decode;
pub mod topic;

/// The wire schema, generated by `prost-build` (through `protox`, so no
/// `protoc` binary is needed — the `thadam-grpc` pattern) from
/// `proto/sparkplug_b.proto`. The proto2 `extensions N to max` ranges have
/// no prost accessors: extension content decodes as unknown fields and is
/// skipped; core Sparkplug B metrics never use them.
#[allow(missing_docs, clippy::all)]
pub mod pb {
    include!(concat!(env!("OUT_DIR"), "/thadam.sparkplug.v1.rs"));
}
